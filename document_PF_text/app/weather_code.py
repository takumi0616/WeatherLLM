def get_weather_code(moji_data_list, first_date, point):
    # pointを'A...'から'C...'に変換
    point_mapping = dict(convert_points)
    point_c = point_mapping.get(point)
    if not point_c:
        raise ValueError(f"Point {point} not found in convert_points")
    # first_dateを利用してCSVファイルのパスを作成
    year_month = first_date[:7]  # 'YYYY-MM'
    csv_date = first_date  # 'YYYY-MM-DD'
    csv_filepath = f"/home/devel/mnt/isilon/archives/PR1H3H/{year_month}/PR-city_{csv_date}.csv"
    # CSVファイルを開いてデータを取得
    import csv
    weather_codes = []
    try:
        with open(csv_filepath, mode='r', encoding='utf-8') as csvfile:
            reader = csv.DictReader(csvfile)
            # '地点番号'がpoint_cと一致する行を探す
            for row in reader:
                if row['地点番号'] == point_c:
                    # '天気03'〜'天気24'のデータを取得
                    times = ['天気03', '天気06', '天気09', '天気12', '天気15', '天気18', '天気21', '天気24']
                    for time in times:
                        weather_codes.append(row[time])
                    break
            else:
                # 該当する地点番号が見つからない場合
                raise ValueError(f"Point {point_c} not found in CSV file")
    except FileNotFoundError:
        raise FileNotFoundError(f"CSV file not found: {csv_filepath}")

    # moji_data_listから'Wd'の値を抽出
    wd_values = []
    for data in moji_data_list:
        if data is not None and 'Wd' in data:
            wd_values.append(data['Wd'])
        else:
            wd_values.append(None)

    return weather_codes, wd_values

